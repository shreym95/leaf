export interface OutboxStore {
  /** Append one entry. Returns its generated id. */
  enqueue(entry: Omit<QueuedEntry, "id">): Promise<string>;
  /** Every queued entry, oldest first. */
  list(): Promise<QueuedEntry[]>;
  /** Drop one entry — called once it has landed, or is confirmed dead. */
  discard(id: string): Promise<void>;
  /**
   * Overwrite a queued entry in place, by its `id` (the same entry, new
   * payload). Optional so existing fakes stay valid; callers fall back to
   * enqueue-then-discard without it.
   */
  put?(entry: QueuedEntry): Promise<void>;
}

// ---------------------------------------------------------------------------
// The conflict rule — §8(b). Pure and independently testable.
// ---------------------------------------------------------------------------

export interface PositionSnapshot {
  percent: number;
  updatedAt: string;
}

/**
 * Furthest-position-wins, not last-write-wins: a queued write from an hour
 * ago must never drag a reader backwards on a device that has since read
 * further. `percent` is the cheap proxy §8 sanctions over `EpubCFI.compare`;
 * `updatedAt` (ISO 8601, lexicographically sortable) breaks an exact tie.
 */
export function isFurtherAlong(
  current: PositionSnapshot | null,
  queued: PositionSnapshot,
): boolean {
  if (!current) return true;
  if (queued.percent > current.percent) return true;
  if (queued.percent < current.percent) return false;
  return queued.updatedAt >= current.updatedAt;
}

/**
 * Newest-write-wins for a queued reading-state replay. The queued write is
 * stale only when the server row was written AFTER the entry was created
 * (`serverUpdatedAt > queuedTs`); an equal timestamp applies. The position
 * is deliberately not compared, so a backwards move the reader made on
 * purpose still lands. An hour-old offline queue still loses to a newer write
 * from another device, because that device's row is newer than the entry.
 */
export function isQueuedWriteStale(serverUpdatedAt: string, queuedTs: number): boolean {
  return Date.parse(serverUpdatedAt) > queuedTs;
}

// ---------------------------------------------------------------------------
// Failure classification — transport (retry) vs. rejection (discard).
// ---------------------------------------------------------------------------

export type WriteFailure = "transport" | "rejected";

/**
 * A genuine Postgrest/Postgres error — RLS denial, a missing FK, invalid
 * input — always carries a structured `code` string: the request reached the
 * server and was refused. A connectivity failure (offline, DNS, timeout, the
 * tab dying mid-request) surfaces as a plain `TypeError` / "Failed to fetch"
 * with no such field. `SupabaseNotConfiguredError` (env not wired) is neither
 * — there is no backend to ever replay against, so treat it the same as a
 * rejection: nothing worth queuing.
 *
 * This is a heuristic on `supabase-js`'s documented error shape, not a
 * guarantee — see the test file and the final report for what would need a
 * real browser/Supabase project to confirm end-to-end.
 *
 * A validation RangeError is a rejection too: nothing can be retried into a
 * valid value, so queuing it would retry forever.
 */
export function classifyWriteFailure(err: unknown): WriteFailure {
  // A RangeError is client-side validation (`annotations.ts`) refusing a value
  // before any round trip. Retrying cannot change that answer.
  if (err instanceof RangeError) return "rejected";
  if (err && typeof err === "object") {
    const e = err as { code?: unknown; name?: unknown };
    if (e.name === "SupabaseNotConfiguredError") return "rejected";
    if (typeof e.code === "string" && e.code.length > 0) return "rejected";
  }
  return "transport";
}

// ---------------------------------------------------------------------------
// Offline-tolerant identity resolution.
//
// `auth.getUser()` revalidates against the Auth server — exactly the network
// round trip that fails offline. `auth.getSession()` reads the stored session
// back out of local storage, so it is how we learn *who* a write belongs to
// once `getUser()` has failed for being offline. It is used ONLY to address a
// queued write; the online path is untouched and keeps using `getUser()` first.
//
// Caveat: `getSession()` needs no network only while the access token is
// unexpired (~1h). After that it tries a refresh, which fails offline, and
// RESOLVES `{ session: null, error: AuthRetryableFetchError }` while the
// stored session survives. `./identity.ts` classifies that as "unverifiable"
// and falls back to the owner marker (the last verified user id on this
// device) — see its header for why that is safe (RLS still guards the replay).
// ---------------------------------------------------------------------------

interface MinimalAuthClient {
  auth: {
    getUser: () => Promise<{
      data: { user: { id: string } | null };
      error?: unknown;
    }>;
    getSession: () => Promise<{
      data: { session: { user: { id: string } } | null };
      error?: unknown;
    }>;
  };
}

/**
 * `getUser()`, falling back to the cached session when the Auth server is
 * unreachable. Null means "signed out" or "no identity we can safely queue
 * against" — either way, drop.
 *
 * auth-js does NOT throw on a network failure: it catches the
 * `AuthRetryableFetchError` and RESOLVES `{ data: { user: null }, error }`.
 * So the offline case is an `error` that is a retryable fetch error, not an
 * exception. Only that error falls back to the cached session. Any other
 * error (e.g. `AuthSessionMissingError`) or no error with no user means the
 * server — or the local storage — says nobody is signed in: return null and
 * never queue against a cached id the server just disowned. A thrown
 * `getUser()` (defensive; not what auth-js does) also falls back.
 */
export async function resolveUserId(
  supabase: MinimalAuthClient,
): Promise<string | null> {
  try {
    const {
      data: { user },
      error,
    } = await supabase.auth.getUser();
    if (user) return user.id;
    if (error && isAuthRetryableFetchError(error)) {
      return getCachedUserId(supabase);
    }
    return null;
  } catch {
    return getCachedUserId(supabase);
  }
}

/** The locally cached identity's user id, with no network round trip. Used
 *  directly by the page-hide flush (D8), where even attempting the network
 *  is the thing we're trying to avoid. The session's id when signed in; the
 *  owner marker's id when the session is unverifiable (access token expired
 *  while offline); null when signed out. Never throws. */
export async function getCachedUserId(
  supabase: MinimalAuthClient,
): Promise<string | null> {
  return identityUserId(await readLocalIdentity(supabase));
}

// ---------------------------------------------------------------------------
// Replay engine — generic over `OutboxStore` and `ReplayHandler`. This is the
// part `outbox.test.ts` drives directly with a fake store + fake handlers.
// ---------------------------------------------------------------------------

/**
 * `applied`  — the write happened.
 * `skipped`  — correctly did nothing (a stale queued position, or a delete
 *              whose row is already gone) — success, not failure.
 * `rejected` — a non-network failure (RLS, bad data, no backend configured).
 * `transport`— a connectivity failure; leave the entry queued.
 */
export type ReplayOutcome = "applied" | "skipped" | "rejected" | "transport";

export type ReplayHandler = (entry: QueuedEntry) => Promise<ReplayOutcome>;

export interface DrainResult {
  applied: number;
  skipped: number;
  rejected: number;
  requeued: number;
}

/** Web Lock held for one whole flush pass, across every tab of this origin. */
const FLUSH_LOCK = "leaf-outbox-flush";
/** Web Lock held for one queue read-modify-write, across every tab. Short: IndexedDB only, never the network. */
const QUEUE_LOCK = "leaf-outbox-queue";

/**
 * Runs `task` under a cross-tab Web Lock when the browser has one. Without it
 * (no Web Locks API) the per-tab chain / single-flight is the only guard.
 */
function withCrossTabLock<T>(name: string, task: () => Promise<T>): Promise<T> {
  const locks = typeof navigator === "undefined" ? undefined : navigator.locks;
  if (!locks || typeof locks.request !== "function") return task();
  // The lock is held until the callback's promise settles; `task`'s outcome is
  // forwarded to the caller, so the lock promise itself carries no value.
  return new Promise<T>((resolve, reject) => {
    locks.request(name, () => task().then(resolve, reject)).catch(reject);
  });
}

/**
 * Serialises every read-modify-write of the queue. Per tab it is a chain; across
 * tabs it is the `QUEUE_LOCK` Web Lock. Without the cross-tab part, a flush in
 * another tab could settle an entry (read its rev, then discard it) between an
 * enqueue's read and its `put`, and the discard would drop the newer payload.
 * Without the per-tab part, a flush could mark an entry `attempted` after an
 * enqueue had cancelled it, and `IDBObjectStore.put` would resurrect it.
 * Nothing run under the lock awaits another locked call.
 */
let queueChain: Promise<unknown> = Promise.resolve();
function withQueueLock<T>(task: () => Promise<T>): Promise<T> {
  const run = queueChain.then(() => withCrossTabLock(QUEUE_LOCK, task));
  queueChain = run.catch(() => undefined);
  return run;
}

/**
 * Per-request ceiling for one replay handler call. A handler whose request
 * never settles (a dead socket with no error, a stalled tab) would otherwise
 * hold the single-flight `running` promise forever: no later pass would run.
 */
export const HANDLER_TIMEOUT_MS = 20_000;

/** This many transport failures in a row, on different items, end the pass:
 *  the network is probably down, and every further attempt would only fail. */
export const TRANSPORT_STREAK_LIMIT = 3;

/**
 * One handler call still in flight on the wire. It ends when the request itself
 * settles, not when the timeout fires: a timed-out call is abandoned by the pass
 * but may still land on the server, so nothing newer for its item may start
 * until it has settled.
 */
interface Attempt {
  key: string;
  settled: Promise<void>;
}

/** Unsettled attempts per store, by entry id. In memory only: a reload forgets
 *  them, and that is safe because a reload also ends any request in flight. */
const attemptsByStore = new WeakMap<OutboxStore, Map<string, Attempt>>();

function attemptsFor(store: OutboxStore): Map<string, Attempt> {
  let attempts = attemptsByStore.get(store);
  if (!attempts) {
    attempts = new Map();
    attemptsByStore.set(store, attempts);
  }
  return attempts;
}

/** An unsettled attempt for any entry of `key`, if one exists. */
function unsettledAttemptFor(attempts: Map<string, Attempt>, key: string): Attempt | undefined {
  for (const attempt of attempts.values()) {
    if (attempt.key === key) return attempt;
  }
  return undefined;
}

/** One handler call, bounded by `HANDLER_TIMEOUT_MS`. A throw or a timeout is a
 *  transport failure: the entry stays queued and `attempted` stays set. The
 *  attempt is registered in `attempts` until its request settles, timeout or not. */
async function applyWithTimeout(
  handler: ReplayHandler,
  entry: QueuedEntry,
  attempts: Map<string, Attempt>,
): Promise<ReplayOutcome> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  const call = Promise.resolve().then(() => handler(entry));
  const attempt: Attempt = {
    key: entry.key,
    settled: call.then(
      () => undefined,
      () => undefined,
    ).then(() => {
      if (attempts.get(entry.id) === attempt) attempts.delete(entry.id);
    }),
  };
  attempts.set(entry.id, attempt);
  const timeout = new Promise<ReplayOutcome>((resolve) => {
    timer = setTimeout(() => resolve("transport"), HANDLER_TIMEOUT_MS);
  });
  try {
    return await Promise.race([call, timeout]);
  } catch {
    // A handler must not throw, but if one slips through, be conservative
    // and retry later rather than lose the write.
    return "transport";
  } finally {
    clearTimeout(timer);
  }
}

/** The stored copy of an entry, or undefined once it has been discarded. */
async function liveEntry(store: OutboxStore, id: string): Promise<QueuedEntry | undefined> {
  return (await store.list()).find((e) => e.id === id);
}

interface PassOutcome {
  result: DrainResult;
  /** An entry was edited while it applied. It is kept, and the pass stops so
   *  that it re-applies before anything queued behind it. */
  changed: boolean;
  /** The transport-failure streak limit stopped the pass. Nothing behind it was attempted. */
  stopped: boolean;
  /** Settle signals of the unsettled attempts that blocked an item this pass. */
  waiting: Promise<void>[];
}

/**
 * One FIFO pass over the queue. Per entry:
 *   1. mark it `attempted` (persisted before the network, so a reload or a
 *      lost response still knows a request may have landed);
 *   2. apply it through its handler (bounded by `HANDLER_TIMEOUT_MS`);
 *   3. discard it only if its `rev` is unchanged. A changed entry is kept and
 *      the pass stops, so the latest payload is re-applied first (B2).
 * A transport failure leaves the entry queued and blocks only its own item
 * key for the rest of this pass: later entries with that key are skipped (per-
 * item FIFO, B3), and entries of other keys carry on. After
 * `TRANSPORT_STREAK_LIMIT` transport failures in a row the pass stops.
 */
async function runPass(
  store: OutboxStore,
  handlers: Partial<Record<OutboxKind, ReplayHandler>>,
): Promise<PassOutcome> {
  const result: DrainResult = { applied: 0, skipped: 0, rejected: 0, requeued: 0 };
  const outcome: PassOutcome = { result, changed: false, stopped: false, waiting: [] };
  const attempts = attemptsFor(store);
  const snapshot = await store.list();
  const blockedKeys = new Set<string>();
  let transportStreak = 0;
  for (const seen of snapshot) {
    const handler = handlers[seen.kind];
    if (!handler) continue;
    // An earlier entry of this item failed in transport: this one must not overtake it.
    if (blockedKeys.has(seen.key)) continue;
    // A timed-out request for this item may still be in flight. Never overlap it:
    // the item is blocked for this pass (not a transport streak), and the flusher
    // runs again once that request settles.
    const inFlight = unsettledAttemptFor(attempts, seen.key);    if (inFlight) {
      blockedKeys.add(seen.key);
      outcome.waiting.push(inFlight.settled);
      continue;
    }

    // Read the live copy: the snapshot can be stale by now (cancelled, replaced).
    const applying = await withQueueLock(async () => {
      const live = await liveEntry(store, seen.id);
      if (!live) return undefined;
      if (!store.put || live.attempted) return live;
      const marked: QueuedEntry = { ...live, attempted: true };
      await store.put(marked);
      return marked;
    });
    if (!applying) continue;

    const verdict = await applyWithTimeout(handler, applying, attempts);

    const settled = await withQueueLock(async () => {
      const now = await liveEntry(store, applying.id);
      if (!now) return "gone" as const;
      if ((now.rev ?? 0) !== (applying.rev ?? 0)) return "changed" as const;
      if (verdict !== "transport") await store.discard(applying.id);
      return "settled" as const;
    });

    if (settled === "changed") {
      outcome.changed = true;
      break;
    }
    if (verdict === "transport") {
      result.requeued += 1;
      blockedKeys.add(seen.key);
      transportStreak += 1;
      if (transportStreak >= TRANSPORT_STREAK_LIMIT) {
        outcome.stopped = true;
        break;
      }
      continue;
    }
    transportStreak = 0;
    if (verdict === "applied") result.applied += 1;
    else if (verdict === "skipped") result.skipped += 1;
    else result.rejected += 1;
  }
  return outcome;
}

/** One pass under the cross-tab flush lock. Two tabs must never replay the same
 *  queue at once: the older payload could land after the newer one. */
function lockedPass(
  store: OutboxStore,
  handlers: () => Partial<Record<OutboxKind, ReplayHandler>>,
): Promise<PassOutcome> {
  return withCrossTabLock(FLUSH_LOCK, () => runPass(store, handlers()));
}

/** Replay every queued entry once, oldest first. An entry a handler doesn't
 *  recognise is left alone (forward compatibility), not discarded. A transport
 *  failure leaves that item's later entries queued, in order; other items
 *  carry on, until `TRANSPORT_STREAK_LIMIT` failures in a row stop the pass. */
export async function drain(
  store: OutboxStore,
  handlers: Partial<Record<OutboxKind, ReplayHandler>>,
): Promise<DrainResult> {
  return (await lockedPass(store, () => handlers)).result;
}

export interface Flusher {
  /** Run a pass now. Requested while one is running: exactly one more pass
   *  runs after it. Resolves when the queue has no more applicable work, or a
   *  transport-failure streak stopped it. Never rejects. */
  flush(): Promise<void>;
  /** Resolves once no flush is running. Never rejects. */
  idle(): Promise<void>;
}

/** Single-flight replay over one store. The real outbox and the tests share it. */
export function createFlusher(
  store: OutboxStore,
  handlers: () => Partial<Record<OutboxKind, ReplayHandler>>,
): Flusher {
  let running: Promise<void> | undefined;
  let requested = false;

  async function loop(): Promise<void> {
    try {
      let again = true;
      while (again) {
        requested = false;
        const pass = await lockedPass(store, handlers);
        // An item was blocked behind a timed-out request that has not settled yet.
        // Flush again once it does, so the newer write goes out right after it.
        for (const settled of pass.waiting) void settled.then(() => flush());
        // Re-run for an entry that changed mid-apply, or for a request that
        // arrived while this pass ran. A streak stop waits for the next
        // request (online, load) rather than spinning offline.
        again = pass.changed || requested;
      }
    } catch {
      // never let a replay failure surface anywhere
    } finally {
      running = undefined;
    }
  }

  function flush(): Promise<void> {
    if (running) {
      requested = true;
      return running;
    }
    running = loop();
    return running;
  }

  return {
    flush,
    async idle() {
      while (running) await running;
    },
  };
}

/** Find the first still-queued entry matching `kind` + `key`, if any. */
export async function findPending(
  store: OutboxStore,
  kind: OutboxKind,
  key: string,
): Promise<QueuedEntry | undefined> {
  const entries = await store.list();
  return entries.find((e) => e.kind === kind && e.key === key);
}

/** Cancel a still-queued entry by kind + key, under the queue lock. Returns
 *  whether one was found. Used to drop a queued `*-create` when its optimistic
 *  record is deleted before ever reaching the server — see
 *  `enqueueBookmarkDelete` / `enqueueHighlightDelete` below for why that matters. */
export function cancelPending(
  store: OutboxStore,
  kind: OutboxKind,
  key: string,
): Promise<boolean> {
  return withQueueLock(() => cancelPendingNow(store, kind, key));
}

/** `cancelPending` without taking the lock, for callers already inside it. */
async function cancelPendingNow(
  store: OutboxStore,
  kind: OutboxKind,
  key: string,
): Promise<boolean> {
  const entry = await findPending(store, kind, key);
  if (!entry) return false;
  await store.discard(entry.id);
  return true;
}

// ---------------------------------------------------------------------------
// IndexedDB-backed store — the real thing. Every operation is wrapped so a
// missing, blocked, or erroring IndexedDB degrades to "the write is dropped",
// exactly like today, rather than breaking reading.
// ---------------------------------------------------------------------------

const DB_NAME = "leaf-outbox";
const DB_VERSION = 1;
const STORE_NAME = "entries";

function idbAvailable(): boolean {
  try {
    return typeof indexedDB !== "undefined";
  } catch {
    return false;
  }
}

function openDb(): Promise<IDBDatabase | undefined> {
  return new Promise((resolve) => {
    if (!idbAvailable()) {
      resolve(undefined);
      return;
    }
    try {
      const req = indexedDB.open(DB_NAME, DB_VERSION);
      req.onupgradeneeded = () => {
        const db = req.result;
        if (!db.objectStoreNames.contains(STORE_NAME)) {
          db.createObjectStore(STORE_NAME, { keyPath: "id" });
        }
      };
      req.onsuccess = () => resolve(req.result);
      req.onerror = () => resolve(undefined);
      req.onblocked = () => resolve(undefined);
    } catch {
      resolve(undefined);
    }
  });
}

/**
 * One connection, shared by every operation. Opening per call leaked a handle
 * each time, and a live handle blocks a later `DB_VERSION` upgrade with
 * `onblocked` — the failure `openDb` already degrades on. Dropped on
 * `versionchange`/`close`, and guarded by the `IDBFactory` it was opened from,
 * since a handle is only valid for its own factory (tests swap the global).
 * A failed open is never memoised: storage can become available again.
 */
let dbPromise: Promise<IDBDatabase | undefined> | undefined;
let dbFactory: IDBFactory | undefined;

function currentFactory(): IDBFactory | undefined {
  try {
    return typeof indexedDB === "undefined" ? undefined : indexedDB;
  } catch {
    return undefined;
  }
}

function getDb(): Promise<IDBDatabase | undefined> {
  const factory = currentFactory();
  if (!factory) return Promise.resolve(undefined);
  if (dbPromise && dbFactory === factory) return dbPromise;

  dbFactory = factory;
  const pending = openDb().then((db) => {
    if (!db) {
      if (dbPromise === pending) dbPromise = undefined;
      return undefined;
    }
    db.onversionchange = () => {
      db.close();
      if (dbPromise === pending) dbPromise = undefined;
    };
    db.onclose = () => {
      if (dbPromise === pending) dbPromise = undefined;
    };
    return db;
  });
  dbPromise = pending;
  return pending;
}

let idSeq = 0;
/** Chronologically sortable (string keys sort lexicographically in
 *  IndexedDB, and `Date.now()` only grows), unique within a session. The
 *  sequence is zero-padded so `"10"` sorts after `"9"` within one millisecond:
 *  replay order is the id order. */
function makeId(): string {
  idSeq += 1;
  return `${Date.now().toString(36)}-${idSeq.toString(36).padStart(6, "0")}-${Math.random()
    .toString(36)
    .slice(2, 8)}`;
}

/** The real store. Every method resolves to a no-op / empty result on any
 *  kind of storage failure — never throws. */
export function createIndexedDbStore(): OutboxStore {
  return {
    async enqueue(entry) {
      const id = makeId();
      try {
        const db = await getDb();
        if (!db) return id; // no IndexedDB — the write is simply not queued
        await new Promise<void>((resolve) => {
          try {
            const tx = db.transaction(STORE_NAME, "readwrite");
            tx.objectStore(STORE_NAME).add({ ...entry, id });
            tx.oncomplete = () => resolve();
            tx.onerror = () => resolve();
            tx.onabort = () => resolve();
          } catch {
            resolve();
          }
        });
      } catch {
        // degrade silently
      }
      return id;
    },

    async list() {
      try {
        const db = await getDb();
        if (!db) return [];
        return await new Promise<QueuedEntry[]>((resolve) => {
          try {
            const tx = db.transaction(STORE_NAME, "readonly");
            const req = tx.objectStore(STORE_NAME).getAll();
            req.onsuccess = () => resolve((req.result as QueuedEntry[]) ?? []);
            req.onerror = () => resolve([]);
          } catch {
            resolve([]);
          }
        });
      } catch {
        return [];
      }
    },

    async put(entry) {
      try {
        const db = await getDb();
        if (!db) return;
        await new Promise<void>((resolve) => {
          try {
            const tx = db.transaction(STORE_NAME, "readwrite");
            tx.objectStore(STORE_NAME).put(entry);
            tx.oncomplete = () => resolve();
            tx.onerror = () => resolve();
            tx.onabort = () => resolve();
          } catch {
            resolve();
          }
        });
      } catch {
        // degrade silently
      }
    },

    async discard(id) {
      try {
        const db = await getDb();
        if (!db) return;
        await new Promise<void>((resolve) => {
          try {
            const tx = db.transaction(STORE_NAME, "readwrite");
            tx.objectStore(STORE_NAME).delete(id);
            tx.oncomplete = () => resolve();
            tx.onerror = () => resolve();
            tx.onabort = () => resolve();
          } catch {
            resolve();
          }
        });
      } catch {
        // degrade silently
      }
    },
  };
}

// A single store instance for the whole tab — real IndexedDB is fine to
// share across every enqueue/replay call.
const store: OutboxStore = createIndexedDbStore();

