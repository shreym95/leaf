function readingStateHandler(): ReplayHandler {
  return async (entry) => {
    const p = entry.payload as ReadingStatePayload;
    try {
      const supabase = createClient();
      const current = await getReadingState(p.userId, p.bookId, supabase);
      if (current && isQueuedWriteStale(current.updated_at, entry.ts)) {
        return "skipped"; // stale — the server row was written after this entry
      }
      // Stamp the row with when the reader was at this position, so a later
      // queued entry is compared against the right time, not the replay time.
      await upsertReadingState(
        p.userId,
        p.bookId,
        { cfi: p.cfi, percent: p.percent, updatedAt: new Date(entry.ts).toISOString() },
        supabase,
      );
      return "applied";
    } catch (err) {
      return classifyWriteFailure(err);
    }
  };
}

/** One annotation write: run it against the annotations client, classify any failure. */
function annotationHandler(
  run: (entry: QueuedEntry, client: ReturnType<typeof createClient>) => Promise<unknown>,
): ReplayHandler {
  return async (entry) => {
    try {
      await run(entry, createClient());
      return "applied";
    } catch (err) {
      return classifyWriteFailure(err);
    }
  };
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Legacy creates carry a `local-…` id that the server never saw, so the server
 * assigns the row's id (as the old client did). An id that is already a UUID
 * is kept, so the replayed row has the same id as the queued entry.
 */
function keepableId(localId: string): string | undefined {
  return UUID_RE.test(localId) ? localId : undefined;
}

